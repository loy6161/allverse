/** ゲスト専用の髪型id。選択肢には出さない＝ログイン済みの人はこの姿になれない */
export const GUEST_HAIR = 'none';

// ⚠ src/avatar.js の AVATAR_PARTS と同じ数を持つ。**増やしたらここも直す**。
//   （wireに乗るのは番号なので、数が食い違うと別の色になる。
//    PRESENCE_SPEC 付録Aと同じ「両側で守る取り決め」の一種）
const BODY_COLOR_COUNT = 8; // AVATAR_PARTS.bodyColors
const COLOR14_COUNT = 14; // hairColors / shirtColors / eyeColors / penlightColors

/**
 * 文字列から安定した32bitの数を作る（FNV-1a）。
 * 暗号用途ではない。ここで欲しいのは「同じ入力なら毎回同じ結果」だけ。
 * crypto を使わないのは、ブラウザとNodeで同じ結果を出す必要があるため。
 */
function hash32(str) {
  let h = 0x811c9dc5;
  const s = String(str == null ? '' : str);
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    // FNV素数 16777619 の掛け算を32bitで行う
    h = (h + ((h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24))) >>> 0;
  }
  return h >>> 0;
}

/**
 * ゲストの見た目を、その人の匿名IDから決める。
 *
 * 同じブラウザなら**毎回まったく同じ姿**になるので、
 * 「あの黄色いゲスト、また来てる」が成立する（入り直しても変わらない）。
 *
 * @param {string} visitor 入場ログと同じ匿名ID。**接頭辞を含めた完全な形**で渡すこと
 *   （ゲストは `g:<番号>`、ログイン済みは `u:<ハッシュ>`）。
 *   ⚠ 接頭辞を落とすと別の色になる。サーバーは接頭辞つきで呼ぶので、
 *     クライアント側のプレビューも必ず同じ形にすること
 * @returns {{h:string,o:string,ac:string,hc:number,sc:number,bc:number,ec:number,pl:number}}
 */
export function guestLookFor(visitor) {
  const h = hash32(visitor);
  // 肌と服で別々の値を使う。同じ数から取ると色が連動して偏るため、
  // 上位ビットと下位ビットに分けて独立させる
  const bc = h % BODY_COLOR_COUNT;
  const sc = (h >>> 8) % COLOR14_COUNT;
  return {
    h: GUEST_HAIR, // 髪なし（ゲストの目印）
    o: 'middle', // 服の形は固定。形は密集すると見分けがつかないため
    ac: 'none', // アクセなし
    hc: 0, // 髪が無いので使われない
    sc, // 服の色（面積が広く、遠目で効く）
    bc, // 肌の色（髪が無いぶん頭がまるごと色面になる＝一番効く）
    ec: 0, // 目の色は既定（近くでしか見えないので識別に使わない）
    pl: 0, // ペンライトの色。ゲストはエモートを使えないので出番がない
    ht: 'mid', // 身長は標準で固定（ゲストは見た目を選べない方針のため）
  };
}
