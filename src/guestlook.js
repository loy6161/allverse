// なぜサーバーが決めるのか:
//   ゲストは見た目を選べない方針（2026-07-29）だが、実装は
//   「入場画面でランダムに決めた姿をクライアントが持ち、サーバーが固定の姿に差し替える」
//   という形になっていた。その結果、**本人の画面と他人の画面で姿が違う**という
//   誰も気づけない食い違いが起きていた（2026-08-02 実測で発覚）。
//   クライアントの申告を一切使わず、サーバーが決めて本人にも返す形に改めた。
//
// なぜ髪なしなのか（2026-08-02 loyさん決定）:
//   ゲストを一目で見分けたい。服の形は人が密集すると埋もれるが、
//   **髪型のシルエットは遠目でも読める**。専用の髪型を作る案もあったが、
//   「髪の毛なし」なら**新しい3Dアセットが要らない**うえ、
//   頭がまるごと肌色の面になるので**色による個体識別が一番強くなる**。
//
// なぜ色をランダムにするのか:
//   全ゲストが同じ姿だと、荒らしがいても「どのゲストか」を指させない。
//   キック（2026-08-02追加）は一覧から名前を選ぶので、
//   目の前の人とリストの名前を結びつけられないと機能しない。
//   「あの黄色いゲスト」が成立することが、モデレーションの前提になる。
//
// ⚠ このファイルは**サーバーとクライアントの両方から読む**。
//   three.js など環境に依存するものを import しないこと
//   （サーバー側 server/server.js からも import している）。
