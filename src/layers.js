/**
 * ブルームを掛けない場所を表す**目印のアルファ値**（bloom.js / avatar_glb.js）。
 *
 * loyさん「ブルームはアバターがヒカルだけ？」を受けてアバターを対象外にしたが、
 * 最初の作りは「アバターだけをもう一度描いて型紙を作る」方式だった。
 * これが**人数ぶん描画回数を増やす**（30人で描画コール 297回＝会場ぜんぶとほぼ同じ）。
 * loyさんの実測でブルームON時に 28fps → 14fps に落ちたのはこれが主因
 * （こちらの実測でも 1920x1080・30人で +4.6ms）。
 *
 * そこで**描き直さない**方式に変えた。アバターの材質だけ不透明度を 0.99 にして
 * 描き、bloom.js は「アルファがちょうど 1 ではない画素＝アバター」と判断する。
 * 追加の描画は 0 回。見た目の差も 1% で気づかない（合成のときに 1 へ戻している）。
 *
 * ⚠ 1 との差はこれくらい離しておく必要がある（16bit浮動小数の誤差より十分大きく、
 *   かつ見た目に出ない値）。判定は bloom.js の NO_BLOOM_MIN/MAX と対で使う。
 */
export const NO_BLOOM_ALPHA = 0.99;
